def batchim(w):
    c = w.strip()[-1]
    if "가" <= c <= "힣":
        return (ord(c) - 0xAC00) % 28 != 0
    return c.lower() in "lmnr0136789"


def josa(w, a, b):
    """받침 있으면 a, 없으면 b (예: 이/가, 은/는, 을/를)"""
    return a if batchim(w) else b


def rieul(w):  # 으로/로 (ㄹ받침은 로)
    c = w.strip()[-1]
    if "가" <= c <= "힣" and (ord(c) - 0xAC00) % 28 == 8:
        return "로"
    return josa(w, "으로", "로")


