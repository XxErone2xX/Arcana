NOISE_PRE = ["", "", "", "", "", "아 ", "야 ", "와 ", "음 ", "아니 ", "근데 ", "진짜 ", "하 "]
NOISE_SUF = ["", "", "", "", "", "ㅋㅋ", "ㅠㅠ", "!", "?", "~", ".", " ㅋㅋㅋ", "ㅜ", "..."]

SLOT_RE = re.compile(r"\{([A-Z]+)(이가|은는|을를|이랑|으로|입니다)?\}")


def render(template, values):
    def sub(m):
        name, j = m.group(1), m.group(2)
        w = values[name]
        return w + (JOSA_RULES[j](w) if j else "")
    return SLOT_RE.sub(sub, template)


def sample():
    users, replies = random.choice(TOPICS)
    u, r = random.choice(users), random.choice(replies)
    values = {k: pick(k, list(v) + EXTRA.get(k, [])) for k, v in SLOTS.items()}
    u = render(u, values)
    # 사용자 말에서 이미 나온 단어는 대답에서도 그대로, 아닌 건 새로 뽑힌 값
    r = render(r, values)
    u = random.choice(NOISE_PRE) + u + random.choice(NOISE_SUF)
    if random.random() < 0.2:
        u = u.replace(" ", "")
    return u.strip(), r


def generate(n=60000, seed=0):
    random.seed(seed)
    return [sample() for _ in range(n)]


